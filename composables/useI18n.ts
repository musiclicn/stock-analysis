const currentLang = ref('en');

export const useI18n = () => {
  const initI18n = () => {
    if (import.meta.client) {
      const saved = localStorage.getItem('mp-lang');
      if (saved) currentLang.value = saved;
    }
  };

  const t = (key: string) => {
    return dictionary[currentLang.value]?.[key] || dictionary.en[key] || key;
  };

  const toggleLang = () => {
    currentLang.value = currentLang.value === 'en' ? 'zh' : 'en';
    if (import.meta.client) localStorage.setItem('mp-lang', currentLang.value);
  };

  return { currentLang, t, toggleLang, initI18n };
};
